package com.attendx.util;

import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;

import java.awt.Color;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

public class PdfExporter {

    public static void exportAttendanceReport(File file, String title, String[] headers, List<String[]> dataRows) throws IOException {
        Document document = new Document(PageSize.A4.rotate(), 36, 36, 40, 40);
        try (FileOutputStream fos = new FileOutputStream(file)) {
            PdfWriter.getInstance(document, fos);
            document.open();

            // Document Header
            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, new Color(99, 91, 255));
            Paragraph titlePara = new Paragraph("AttendX – Smart Attendance Management System", titleFont);
            titlePara.setAlignment(Element.ALIGN_CENTER);
            document.add(titlePara);

            Font subFont = FontFactory.getFont(FontFactory.HELVETICA, 12, Color.DARK_GRAY);
            Paragraph subPara = new Paragraph(title, subFont);
            subPara.setAlignment(Element.ALIGN_CENTER);
            subPara.setSpacingAfter(15);
            document.add(subPara);

            // Table
            PdfPTable table = new PdfPTable(headers.length);
            table.setWidthPercentage(100);

            // Header cells
            Font headerFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, Color.WHITE);
            for (String h : headers) {
                PdfPCell cell = new PdfPCell(new Phrase(h, headerFont));
                cell.setBackgroundColor(new Color(99, 91, 255));
                cell.setPadding(8);
                cell.setHorizontalAlignment(Element.ALIGN_CENTER);
                table.addCell(cell);
            }

            // Data cells
            Font bodyFont = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.BLACK);
            boolean alternate = false;
            if (dataRows != null) {
                for (String[] row : dataRows) {
                    Color rowBg = alternate ? new Color(248, 249, 250) : Color.WHITE;
                    for (String val : row) {
                        PdfPCell cell = new PdfPCell(new Phrase(val != null ? val : "", bodyFont));
                        cell.setBackgroundColor(rowBg);
                        cell.setPadding(6);
                        table.addCell(cell);
                    }
                    alternate = !alternate;
                }
            }

            document.add(table);

            // Footer
            Font footerFont = FontFactory.getFont(FontFactory.HELVETICA, 8, Color.GRAY);
            String timestamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
            Paragraph footerPara = new Paragraph("Generated by AttendX on " + timestamp + " | Confidential Academic Record", footerFont);
            footerPara.setAlignment(Element.ALIGN_RIGHT);
            footerPara.setSpacingBefore(15);
            document.add(footerPara);

            document.close();
        } catch (DocumentException e) {
            throw new IOException("Failed to create PDF document: " + e.getMessage(), e);
        }
    }

    private PdfExporter() {}
}
